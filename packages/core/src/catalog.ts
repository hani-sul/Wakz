const https = (url: string, label?: string): CheckTarget => ({
  kind: 'https',
  target: url,
  // 401/403/404/412/429 still prove the endpoint answered: they are not connectivity failures.
  expectStatus: [200, 204, 301, 302, 307, 308, 400, 401, 403, 404, 405, 412, 429],
  ...(label ? { label } : {}),
});

const dns = (host: string): CheckTarget => ({ kind: 'dns', target: host });
const tcp = (host: string, port = 443): CheckTarget => ({ kind: 'tcp', target: host, port });

