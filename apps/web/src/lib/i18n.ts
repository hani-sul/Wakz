const DICTIONARIES: Record<Locale, Dictionary> = { ar, en };

export function translate(locale: Locale, key: string, variables?: Record<string, string | number>): string {
  const dictionary = DICTIONARIES[locale] ?? DICTIONARIES[DEFAULT_LOCALE];
  const template = dictionary[key] ?? DICTIONARIES.en[key] ?? key;
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(variables[name] ?? `{${name}}`));
}

export function directionFor(locale: Locale): 'rtl' | 'ltr' {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

/** Arabic text with Latin digits keeps latency numbers easy to scan. */
export function localeTag(locale: Locale): string {
  return locale === 'ar' ? 'ar-u-nu-latn' : 'en-GB';
}
