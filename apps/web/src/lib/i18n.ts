export const LOCALE_STORAGE_KEY = 'techpulse.locale';
export const SUPPORTED_LOCALES: Locale[] = ['ar', 'en'];
export const DEFAULT_LOCALE: Locale = 'ar';

/** The interface follows the device language; Arabic is used when the device prefers it. */
export function deviceLocale(): Locale {
  try {
    const languages = [navigator.language, ...(navigator.languages ?? [])];
    return languages.some((language) => /^ar\b/i.test(language)) ? 'ar' : 'en';
  } catch {
    return DEFAULT_LOCALE;
  }
}

